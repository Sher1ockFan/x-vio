#!/usr/bin/env python3
"""Check the built ARM64 API rejects unsupported modes before sensor/file access."""
import os
import shutil
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile

archive=Path(sys.argv[1]).resolve()
cv=Path('/build/orb-kit/opencv-4.8.0/usr/lib')
pango=Path('/build/orb-kit/prefix')
with tempfile.TemporaryDirectory(prefix='mono-imu-mode-') as td:
    root=Path(td)
    with tarfile.open(archive) as tar:
        for m in tar.getmembers():
            assert not Path(m.name).is_absolute() and '..' not in Path(m.name).parts
        tar.extractall(root)
    pkg=root/'mono_imu_vio'
    src=pkg/'source/ORB_SLAM3'
    # g2o's config.h is generated by CMake, not part of the source manifest.
    build=Path(os.environ.get('MONO_IMU_BUILD_ROOT','/build/mono-imu-vio/work'))
    shutil.copy2(build/'source/Thirdparty/g2o/config.h', src/'Thirdparty/g2o/config.h')
    env={**os.environ,'LD_LIBRARY_PATH':str(pkg/'lib')+':'+str(cv)}
    symbols=subprocess.check_output(['nm','-DC',str(pkg/'lib/libORB_SLAM3.so')],text=True,env=env)
    for forbidden in ('System::TrackStereo(', 'System::TrackRGBD(', 'Tracking::GrabImageStereo(', 'Tracking::GrabImageRGBD(', 'Tracking::StereoInitialization(', 'Frame::ComputeStereo'):
        assert forbidden not in symbols, forbidden
    assert 'System::TrackMonocular(' in symbols
    test=root/'mode.cc'
    test.write_text(r'''#include "System.h"
#include "Settings.h"
#include <stdexcept>
#include <iostream>
int main() {
    int rejected = 0;
    for (int mode : {-1,0,1,2,4,5,99}) {
        try { ORB_SLAM3::System system("/no-vocabulary", "/no-config",
              static_cast<ORB_SLAM3::System::eSensor>(mode), false); return 10; }
        catch (const std::invalid_argument&) { ++rejected; }
        try { ORB_SLAM3::Settings settings("/no-config",mode); return 11; }
        catch (const std::invalid_argument&) { ++rejected; }
    }
    std::cout << "UNSUPPORTED_MODE_REJECTED " << rejected << std::endl;
    return rejected == 14 ? 0 : 12;
}
''')
    flags=['g++-11','-std=c++17','-include','unistd.h','-include','boost/serialization/library_version_type.hpp',
           '-I'+str(src),'-I'+str(src/'include'),'-I'+str(src/'include/CameraModels'),'-I'+str(src/'Thirdparty/Sophus'),
           '-isystem','/usr/include/eigen3','-isystem',str(cv.parent/'include/opencv4'),'-isystem',str(pango/'include'),
           str(test),'-o',str(root/'mode'),'-L'+str(pkg/'lib'),'-L'+str(cv),'-Wl,-rpath-link,'+str(cv),'-Wl,-rpath-link,'+str(pkg/'lib'),
           '-lORB_SLAM3','-lpangolin','-lopencv_core','-lOpenGL','-lGLX','-lGLU','-lGLEW','-lEGL','-lX11','-pthread']
    subprocess.run(flags,check=True,env=env,stdout=subprocess.DEVNULL)
    subprocess.run([str(root/'mode')],check=True,env=env,timeout=10)
    print('NATIVE_MODE_CONTRACT_PASS')
